bool Odometry_Config_IsCorrectEncoder (const eEncoder_t encoder) {
    return (encoder >= eEncoder_First) && (encoder < eEncoder_Last);
}

const sEncoderDesc_t *Odometry_Config_GetEncoderDesc (const eEncoder_t encoder) {
    if (!Odometry_Config_IsCorrectEncoder(encoder)) {
        return NULL;
    }

    return &g_static_encoder_lut[encoder];
}
